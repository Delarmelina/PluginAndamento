import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp,mkdir,copyFile,rm,readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { spawnSync } from 'node:child_process';
const hookPath=fileURLToPath(new URL('../hooks/context.mjs',import.meta.url));
const promptHook=event=>spawnSync(process.execPath,[hookPath],{input:JSON.stringify(event),encoding:'utf8'});
test('MCP: painel, recursos e marcos reais via stdio',async t=>{
 const directory=await mkdtemp(join(tmpdir(),'andamento-mcp-'));
 const packageJson=JSON.parse(await readFile(new URL('../package.json',import.meta.url),'utf8'));
 assert.match(packageJson.scripts.build,/esbuild .*--bundle/);
 assert.ok(packageJson.dependencies['@modelcontextprotocol/sdk']);
 assert.ok(packageJson.dependencies.zod);
 const config=JSON.parse(await readFile(new URL('../mcp.json',import.meta.url),'utf8')).mcpServers.andamento;
 assert.equal(config.type,'stdio');
 assert.equal(config.command,'node');
 assert.deepEqual(config.args,['${PLUGIN_ROOT}/dist/server.mjs']);
 assert.equal(config.cwd,'${PLUGIN_ROOT}');
 const server=fileURLToPath(new URL('../dist/server.mjs',import.meta.url));
 const bundle=await readFile(server,'utf8');
 const imports=bundle.split(/\r?\n/).filter(line=>/^\s*import\b/.test(line));
 assert.ok(imports.length>0,'o bundle deve importar somente módulos nativos do Node');
 assert.ok(imports.every(line=>/from\s*['"]node:/.test(line)),`imports externos inesperados: ${imports.join('\n')}`);
 const secondaryConfig=JSON.parse(await readFile(new URL('../.mcp.json',import.meta.url),'utf8')).mcpServers.andamento;
 assert.deepEqual(secondaryConfig.args,config.args);
 const runtimeDirectory=await mkdtemp(join(tmpdir(),'andamento-runtime-'));
 await mkdir(join(runtimeDirectory,'dist'));
 await mkdir(join(runtimeDirectory,'ui'));
 await copyFile(server,join(runtimeDirectory,'dist','server.mjs'));
 await copyFile(new URL('../ui/panel.html',import.meta.url),join(runtimeDirectory,'ui','panel.html'));
 const transport=new StdioClientTransport({command:config.command,args:[join(runtimeDirectory,'dist','server.mjs')],cwd:runtimeDirectory,env:{...process.env,ANDAMENTO_DATA_DIR:directory}});
 const client=new Client({name:'andamento-test',version:'1.0.0'});
 t.after(async()=>{await client.close();await rm(directory,{recursive:true,force:true});await rm(runtimeDirectory,{recursive:true,force:true});});
 await client.connect(transport);
 const firstPrompt=promptHook({hook_event_name:'UserPromptSubmit',session_id:'steering-regression',turn_id:'turn-original',prompt:'Inicie o trabalho original.'});
 assert.equal(firstPrompt.status,0);
 assert.equal(JSON.parse(firstPrompt.stdout).hookSpecificOutput.hookEventName,'UserPromptSubmit');
 const tools=await client.listTools();
 const panel=tools.tools.find(t=>t.name==='open_panel');
 assert.deepEqual(panel._meta['openai/ui'].entrypoints,[{type:'global'},{type:'thread'}]);
 assert.deepEqual(panel._meta.ui.visibility,['app']);
 for(const name of ['start_plan','update_step','get_progress','view_progress']){
  assert.equal(tools.tools.find(t=>t.name===name)._meta?.ui?.resourceUri,undefined,'Ferramentas do agente não devem inserir cartões');
 }
 const resource=await client.readResource({uri:panel._meta.ui.resourceUri});
 assert.match(resource.contents[0].text,/ui\/initialize/);
 assert.deepEqual(resource.contents[0]._meta['openai/ui'].availableDisplayModes,['fullscreen']);
 const follow=tools.tools.find(t=>t.name==='follow_progress');
 const conversation=await client.readResource({uri:follow._meta.ui.resourceUri});
 assert.deepEqual(conversation.contents[0]._meta['openai/ui'].availableDisplayModes,['fullscreen']);
 assert.match(conversation.contents[0].text,/<body data-bound-panel="true">/);
 assert.doesNotMatch(conversation.contents[0].text,/requestDisplayMode|confirmFloating/);
 assert.ok(follow.inputSchema.required.includes('threadId'));
 const started=await client.callTool({name:'start_plan',arguments:{threadId:'integration',requestId:'run',title:'Validar integração',steps:['Conectar','Conferir resultado']}});
 assert.equal(started.structuredContent.steps[0].status,'pending');
 const updated=await client.callTool({name:'update_step',arguments:{threadId:'integration',requestId:'run',stepId:'step-1',status:'completed',note:'Conexão MCP verificada'}});
 assert.equal(updated.structuredContent.steps[0].status,'completed');
 const listed=await client.callTool({name:'get_progress',arguments:{threadId:'integration'}});
 assert.equal(listed.structuredContent.plan.steps.length,2,'o painel/agente consegue listar as etapas após atualização');
 const steeredPrompt=promptHook({hook_event_name:'UserPromptSubmit',session_id:'steering-regression',turn_id:'turn-steered',prompt:'Pause a direção anterior e siga esta orientação.'});
 assert.equal(steeredPrompt.status,0,'uma orientação posterior deve continuar sendo aceita pelo hook');
 const hookResult=JSON.parse(steeredPrompt.stdout);
 assert.equal(hookResult.hookSpecificOutput.hookEventName,'UserPromptSubmit');
 assert.match(hookResult.hookSpecificOutput.additionalContext,/"turn-steered"/);
 assert.doesNotMatch(steeredPrompt.stdout,/"decision"\s*:\s*"block"|"updatedInput"\s*:/);
 assert.doesNotMatch(steeredPrompt.stdout,/Pause a direção anterior/,'o hook não reescreve nem consome o texto da orientação');
 const opened=await client.callTool({name:'view_progress',arguments:{threadId:'integration'}});
 assert.equal(opened.structuredContent.plan.title,'Validar integração');
 const lateral=await client.callTool({name:'open_panel',arguments:{}});
 assert.equal(lateral.structuredContent.plan,null);
 assert.equal(lateral.structuredContent.plans[0].threadId,'integration');
 const direct=await client.callTool({name:'follow_progress',arguments:{threadId:'integration'}});
 assert.equal(direct.structuredContent.selectedThreadId,'integration');
 assert.equal(direct.structuredContent.plan.title,'Validar integração');
 assert.deepEqual(direct.structuredContent.plans,[]);
 const rejected=await client.callTool({name:'update_step',arguments:{threadId:'integration',requestId:'run',stepId:'step-2',status:'completed'}});
 assert.equal(rejected.isError,true);
});
