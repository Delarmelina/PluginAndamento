import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp,rm,readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
test('MCP: painel, recursos e marcos reais via stdio',async t=>{
 const directory=await mkdtemp(join(tmpdir(),'andamento-mcp-'));
 const config=JSON.parse(await readFile(new URL('../mcp.json',import.meta.url),'utf8')).mcpServers.andamento;
 assert.equal(config.type,'stdio');
 assert.equal(config.command,'node');
 assert.deepEqual(config.args,['${PLUGIN_ROOT}/server.mjs']);
 assert.equal(config.cwd,'${PLUGIN_ROOT}');
 const server=process.env.ANDAMENTO_TEST_SERVER??fileURLToPath(new URL('../server.mjs',import.meta.url));
 const transport=new StdioClientTransport({command:config.command,args:[server],env:{...process.env,ANDAMENTO_DATA_DIR:directory}});
 const client=new Client({name:'andamento-test',version:'1.0.0'});
 t.after(async()=>{await client.close();await rm(directory,{recursive:true,force:true});});
 await client.connect(transport);
 const tools=await client.listTools();
 const panel=tools.tools.find(t=>t.name==='open_panel');
 assert.deepEqual(panel._meta['openai/ui'].entrypoints,[{type:'global'},{type:'thread'}]);
 assert.deepEqual(panel._meta.ui.visibility,['app']);
 for(const name of ['start_plan','update_step','get_progress','view_progress']){
  assert.equal(tools.tools.find(t=>t.name===name)._meta?.ui?.resourceUri,undefined,'Ferramentas do agente não devem inserir cartões');
 }
 const resource=await client.readResource({uri:panel._meta.ui.resourceUri});
 assert.match(resource.contents[0].text,/ui\/initialize/);
 assert.deepEqual(resource.contents[0]._meta['openai/ui'].availableDisplayModes,['fullscreen']);
 const follow=tools.tools.find(t=>t.name==='follow_progress');
 const conversation=await client.readResource({uri:follow._meta.ui.resourceUri});
 assert.deepEqual(conversation.contents[0]._meta['openai/ui'].availableDisplayModes,['fullscreen']);
 assert.match(conversation.contents[0].text,/<body data-bound-panel="true">/);
 assert.doesNotMatch(conversation.contents[0].text,/requestDisplayMode|confirmFloating/);
 assert.ok(follow.inputSchema.required.includes('threadId'));
 const started=await client.callTool({name:'start_plan',arguments:{threadId:'integration',requestId:'run',title:'Validar integração',steps:['Conectar','Conferir resultado']}});
 assert.equal(started.structuredContent.steps[0].status,'pending');
 const updated=await client.callTool({name:'update_step',arguments:{threadId:'integration',requestId:'run',stepId:'step-1',status:'completed',note:'Conexão MCP verificada'}});
 assert.equal(updated.structuredContent.steps[0].status,'completed');
 const opened=await client.callTool({name:'view_progress',arguments:{threadId:'integration'}});
 assert.equal(opened.structuredContent.plan.title,'Validar integração');
 const lateral=await client.callTool({name:'open_panel',arguments:{}});
 assert.equal(lateral.structuredContent.plan,null);
 assert.equal(lateral.structuredContent.plans[0].threadId,'integration');
 const direct=await client.callTool({name:'follow_progress',arguments:{threadId:'integration'}});
 assert.equal(direct.structuredContent.selectedThreadId,'integration');
 assert.equal(direct.structuredContent.plan.title,'Validar integração');
 assert.deepEqual(direct.structuredContent.plans,[]);
 const rejected=await client.callTool({name:'update_step',arguments:{threadId:'integration',requestId:'run',stepId:'step-2',status:'completed'}});
 assert.equal(rejected.isError,true);
});
